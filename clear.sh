#!/bin/bash

# Укажите исходную директорию с конфигурационными файлами
SOURCE_DIR="./configs"

# Укажите директорию назначения (например, mount)
TARGET_DIR="./mount"

# Создаем директорию назначения, если она не существует
mkdir -p "$TARGET_DIR"

# Копируем файлы и очищаем их содержимое
for file in "$SOURCE_DIR"/*; do
  if [ -f "$file" ]; then
    # Получаем имя файла
    filename=$(basename "$file")
    
    # Копируем файл в директорию назначения
    cp "$file" "$TARGET_DIR/$filename"
    
    # Очищаем содержимое файла в директории назначения
    > "$TARGET_DIR/$filename"
  fi
done

echo "Конфигурационные файлы скопированы и очищены."